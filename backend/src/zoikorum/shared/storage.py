"""Blob storage adapter: uploaded files are kept like normal data.

``DatabaseStorage`` stores files in PostgreSQL (platform.stored_files), so they are backed up and restored with the
database. ``LocalDiskStorage`` is for development and tests only. ZK_STORAGE_PROVIDER=local is refused outside
local/test/development; any other value (including the old gcs, s3 and r2) selects the database. Both keep a key
write-once and refuse deletes except for profile photos (not evidence: a professional can replace or remove theirs).

The one other way a stored file goes is the reviewed retention workflow (shared/retention.py): ``purge_for_retention``
removes a file whose retention period under ZK_RETENTION_RULES has ended. It is only called by that job, which skips
anything under legal hold.
"""

from __future__ import annotations

import hashlib
import logging
import re
from functools import lru_cache
from pathlib import Path
from typing import Protocol

from sqlalchemy import text

from zoikorum.config import get_settings
from zoikorum.shared.errors import ServiceUnavailable, ValidationFailed

log = logging.getLogger("zoikorum.storage")
# Files that may be deleted: profile photos only. Evidence, deliverables, attachments and exports never are.
ERASABLE = re.compile(r"^professionals/[^/]+/photo-[0-9a-f]+$")


def safe_key(key: str) -> str:
    if not key or key.startswith("/") or "\\" in key or "\x00" in key or ".." in key.split("/"):
        raise ValidationFailed("Invalid storage key")
    return key


def refuse_unless_erasable(key: str) -> None:
    if not ERASABLE.match(key):
        # Explicit reviewed erasure handles versions and retention; this path is never it.
        raise ValidationFailed("Cloud evidence deletion requires a reviewed retention workflow", code="RETENTION_REVIEW_REQUIRED")


class BlobStorage(Protocol):
    def put(self, key: str, data: bytes) -> str | None: ...
    def get(self, key: str, version_id: str | None = None) -> bytes | None: ...
    def delete(self, key: str) -> None: ...


class LocalDiskStorage:
    def __init__(self, root: str | Path):
        self.root = Path(root).resolve()

    def _path(self, key: str) -> Path:
        path = (self.root / key).resolve()
        if self.root not in path.parents:  # keys are generated by the app, but never trust a path
            raise ValueError("Invalid storage key")
        return path

    def put(self, key: str, data: bytes) -> None:
        path = self._path(key)
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)

    def get(self, key: str, version_id: str | None = None) -> bytes | None:
        if version_id:
            raise ServiceUnavailable("This object belongs to versioned cloud storage", code="STORAGE_PROVIDER_MISMATCH")
        path = self._path(key)
        return path.read_bytes() if path.is_file() else None

    def delete(self, key: str) -> None:
        self._path(key).unlink(missing_ok=True)

    def purge_for_retention(self, key: str, version_id: str | None = None) -> None:
        self._path(safe_key(key)).unlink(missing_ok=True)



@lru_cache
def _sync_engine():
    """A small synchronous connection pool for file storage (the BlobStorage interface is synchronous)."""
    from sqlalchemy import create_engine
    from sqlalchemy.engine import make_url

    url = make_url(get_settings().database_url).set(drivername="postgresql+psycopg")
    return create_engine(url, pool_size=3, max_overflow=2, pool_pre_ping=True)


class DatabaseStorage:
    """Files kept in PostgreSQL (platform.stored_files), so they are backed up and restored with the rest of the data.
    A key is written once: the same bytes again are accepted, different bytes are refused. No versions (``put``
    returns None). Fine for documents and photos; keep uploads small (see the upload size limits)."""

    def __init__(self, engine=None):
        self.engine = engine or _sync_engine()

    def _failure(self, exc):
        raise ServiceUnavailable("File storage could not complete the operation", code="STORAGE_UNAVAILABLE") from exc

    def put(self, key, data):
        key = safe_key(key)
        digest = hashlib.sha256(data).hexdigest()
        try:
            with self.engine.begin() as conn:
                inserted = conn.execute(text(
                    "INSERT INTO platform.stored_files (id, key, data, sha256, size_bytes) "
                    "VALUES (gen_random_uuid(), :key, :data, :sha, :size) ON CONFLICT (key) DO NOTHING"),
                    {"key": key, "data": data, "sha": digest, "size": len(data)}).rowcount
                if inserted:
                    return None
                current = conn.execute(text("SELECT sha256 FROM platform.stored_files WHERE key = :key"), {"key": key}).scalar()
        except Exception as exc:
            self._failure(exc)
        if current != digest:
            raise ValidationFailed("Committed files cannot be replaced", code="IMMUTABLE_FILE")
        return None

    def get(self, key, version_id=None):
        if version_id:
            raise ServiceUnavailable("This object belongs to versioned cloud storage", code="STORAGE_PROVIDER_MISMATCH")
        try:
            with self.engine.connect() as conn:
                row = conn.execute(text("SELECT data FROM platform.stored_files WHERE key = :key"), {"key": safe_key(key)}).first()
        except Exception as exc:
            self._failure(exc)
        return bytes(row[0]) if row else None

    def delete(self, key):
        refuse_unless_erasable(safe_key(key))
        self._remove(key)

    def purge_for_retention(self, key, version_id=None):
        self._remove(safe_key(key))

    def _remove(self, key):
        try:
            with self.engine.begin() as conn:
                conn.execute(text("DELETE FROM platform.stored_files WHERE key = :key"), {"key": key})
        except Exception as exc:
            self._failure(exc)


def get_storage() -> BlobStorage:
    """'local' is development only; any other provider value (including old 'gcs', 's3', 'r2') means the database."""
    settings = get_settings()
    if settings.storage_provider == "local":
        if settings.env in ("local", "test", "development"):
            return LocalDiskStorage(settings.storage_dir)
        raise ServiceUnavailable("Configure production object storage", code="INTEGRATION_NOT_CONFIGURED")
    return DatabaseStorage()
